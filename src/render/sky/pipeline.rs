pub(super) fn create(
    device: &wgpu::Device,
    format: wgpu::TextureFormat,
    bind: &wgpu::BindGroupLayout,
) -> wgpu::RenderPipeline {
    create_with_source(device, format, bind, super::shader_source())
}

pub(super) fn create_with_source(
    device: &wgpu::Device,
    format: wgpu::TextureFormat,
    bind: &wgpu::BindGroupLayout,
    source: String,
) -> wgpu::RenderPipeline {
    let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {
        label: Some("BSL style sky with volume clouds"),
        source: wgpu::ShaderSource::Wgsl(source.into()),
    });
    let layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
        label: Some("sky pipeline layout"),
        bind_group_layouts: &[Some(bind)],
        immediate_size: 0,
    });
    device.create_render_pipeline(&wgpu::RenderPipelineDescriptor {
        label: Some("volume sky pipeline"),
        layout: Some(&layout),
        vertex: wgpu::VertexState {
            module: &shader,
            entry_point: Some("vs_main"),
            compilation_options: Default::default(),
            buffers: &[],
        },
        primitive: Default::default(),
        depth_stencil: Some(wgpu::DepthStencilState {
            format: super::super::DEPTH_FORMAT,
            depth_write_enabled: Some(false),
            depth_compare: Some(wgpu::CompareFunction::Always),
            stencil: Default::default(),
            bias: Default::default(),
        }),
        multisample: Default::default(),
        fragment: Some(wgpu::FragmentState {
            module: &shader,
            entry_point: Some("fs_main"),
            compilation_options: Default::default(),
            targets: &super::super::scene_ao::color_targets(format, None),
        }),
        multiview_mask: None,
        cache: None,
    })
}
